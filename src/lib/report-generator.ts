/**
 * Builds a self-contained, downloadable HTML report (and the matching email
 * body) for the KLLCTRS weekly/period analytics. Inline CSS only, KLLCTRS brand
 * colors, opens in any browser.
 */

export interface PeriodStats {
  total_page_views: number;
  unique_visitors: number;
  total_logins: number;
  new_signups: number;
  event_views: number;
  card_views: number;
  searches: number;
  trade_requests: number;
  chatbot_queries: number;
  active_users: number;
}

export interface ReportData {
  dateRange: string;
  stats: PeriodStats;
  topPages: { page_path: string; views: number }[];
}

const C = {
  navy: "#151E3C",
  cream: "#FEF9FF",
  amethyst: "#8B5CF6",
  tuscan: "#FCD279",
  bloom: "#EF8799",
  gray: "#8a8f98",
};

function statBox(label: string, value: number, color = C.tuscan): string {
  return `<td style="padding:8px">
    <div style="background:rgba(254,249,255,0.04);border:1px solid rgba(139,92,246,0.2);border-radius:12px;padding:18px">
      <div style="font-size:30px;font-weight:800;color:${color};font-family:Arial,sans-serif">${value.toLocaleString()}</div>
      <div style="font-size:12px;color:${C.gray};margin-top:4px">${label}</div>
    </div>
  </td>`;
}

/** Full standalone HTML document (for download). */
export function generateFullReport(data: ReportData): string {
  const s = data.stats;
  const rows = data.topPages.length
    ? data.topPages
        .map(
          (p) =>
            `<tr><td style="padding:8px 12px;border-bottom:1px solid rgba(139,92,246,0.15);color:${C.cream}">${escapeHtml(p.page_path)}</td>
             <td style="padding:8px 12px;border-bottom:1px solid rgba(139,92,246,0.15);text-align:right;color:${C.tuscan};font-weight:700">${p.views.toLocaleString()}</td></tr>`,
        )
        .join("")
    : `<tr><td colspan="2" style="padding:12px;color:${C.gray}">No page views recorded in this period.</td></tr>`;

  return `<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8" />
<title>KLLCTRS Report — ${escapeHtml(data.dateRange)}</title></head>
<body style="background:${C.navy};color:${C.cream};font-family:Arial,Helvetica,sans-serif;padding:40px;margin:0">
  <div style="max-width:720px;margin:0 auto">
    <h1 style="color:${C.amethyst};margin:0 0 4px">KLLCTRS Platform Report</h1>
    <p style="color:${C.tuscan};margin:0 0 24px">${escapeHtml(data.dateRange)}</p>

    <table role="presentation" width="100%" style="border-collapse:collapse">
      <tr>${statBox("Page views", s.total_page_views)}${statBox("Unique visitors", s.unique_visitors, C.amethyst)}${statBox("New signups", s.new_signups, C.bloom)}${statBox("Active users", s.active_users)}</tr>
      <tr>${statBox("Logins", s.total_logins)}${statBox("Event views", s.event_views, C.amethyst)}${statBox("Card views", s.card_views)}${statBox("Searches", s.searches, C.amethyst)}</tr>
      <tr>${statBox("Trade requests", s.trade_requests, C.bloom)}${statBox("Chatbot queries", s.chatbot_queries)}<td></td><td></td></tr>
    </table>

    <h2 style="color:${C.amethyst};margin:32px 0 8px;font-size:18px">Top pages</h2>
    <table role="presentation" width="100%" style="border-collapse:collapse;background:rgba(254,249,255,0.03);border-radius:12px;overflow:hidden">
      <tr><th style="text-align:left;padding:8px 12px;color:${C.gray};font-size:12px">Page</th><th style="text-align:right;padding:8px 12px;color:${C.gray};font-size:12px">Views</th></tr>
      ${rows}
    </table>

    <p style="color:${C.gray};font-size:12px;margin-top:32px">Generated by KLLCTRS Admin · ${new Date().toISOString().slice(0, 10)}</p>
  </div>
</body></html>`;
}

/** Compact inline-CSS body for the weekly email (no <html> wrapper needed). */
export function generateEmailReport(data: ReportData): string {
  return generateFullReport(data);
}

function escapeHtml(s: string): string {
  return (s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}
